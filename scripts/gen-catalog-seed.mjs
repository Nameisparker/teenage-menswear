/**
 * Regenerates the catalog seed migration from src/lib/products.ts.
 *
 *   npm run seed:sql
 *
 * Keeping the seed generated rather than hand-written means the SQL can never
 * drift from the data the app ships with. Edit products.ts, re-run this, and
 * re-apply the migration.
 *
 * products.ts is TypeScript, so it is compiled to a throwaway directory first
 * using the project's own tsc — no extra dependency.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const OUT = "supabase/migrations/20260824000001_seed_catalog.sql";

/** Placeholder stock per size. Replace with real counts when inventory matters. */
const SEED_STOCK = 25;

const work = mkdtempSync(join(tmpdir(), "catalog-seed-"));

try {
  // Run tsc's JS entry point through this same Node binary. Going via `npx`
  // would mean spawning npx.cmd on Windows, which Node refuses without a shell.
  execFileSync(
    process.execPath,
    [
      "node_modules/typescript/bin/tsc",
      "src/lib/products.ts",
      "src/lib/types.ts",
      "--outDir",
      work,
      "--module",
      "esnext",
      "--target",
      "es2022",
      "--moduleResolution",
      "bundler",
      "--skipLibCheck",
    ],
    { stdio: "inherit" }
  );

  // Lets Node treat the emitted .js as ESM.
  writeFileSync(join(work, "package.json"), '{"type":"module"}');

  const { PRODUCTS, CATEGORIES } = await import(
    pathToFileURL(join(work, "products.js")).href
  );

  /** Single-quote a SQL string literal, doubling any embedded quote. */
  const q = (value) =>
    value === null || value === undefined
      ? "null"
      : `'${String(value).replace(/'/g, "''")}'`;

  const variantRows = PRODUCTS.flatMap((p) =>
    p.sizes.map(
      (size, i) =>
        `  ((select id from public.products where slug = ${q(p.slug)}), ${q(size)}, ${i}, ${SEED_STOCK})`
    )
  );

  const sql = `-- Teenage Menswear — catalog seed
--
-- GENERATED by scripts/gen-catalog-seed.mjs from src/lib/products.ts
-- (${PRODUCTS.length} products, ${CATEGORIES.length} categories, ${variantRows.length} size variants).
-- Do not edit by hand — run \`npm run seed:sql\` instead.
--
-- Idempotent: every insert upserts on its natural key, so applying this twice
-- is harmless and re-applying after an edit updates existing rows.

-- Store settings ------------------------------------------------------------

insert into public.store_settings
  (id, name, short_name, tagline, address, phone_display, phone_href)
values
  (true, 'Teenage Menswear', 'Teenage', 'Everyday menswear, done right.',
   'Kudankulam Road, Radhapuram, Tirunelveli - 627111',
   '+91 93846 26894', 'tel:+919384626894')
on conflict (id) do update set
  name          = excluded.name,
  short_name    = excluded.short_name,
  tagline       = excluded.tagline,
  address       = excluded.address,
  phone_display = excluded.phone_display,
  phone_href    = excluded.phone_href;

-- Categories ----------------------------------------------------------------

insert into public.categories (slug, label, sort_order) values
${CATEGORIES.map((c, i) => `  (${q(c.value)}, ${q(c.label)}, ${i})`).join(",\n")}
on conflict (slug) do update set
  label      = excluded.label,
  sort_order = excluded.sort_order;

-- Products ------------------------------------------------------------------
--
-- category_id is resolved by slug, so this seed never hard-codes a uuid.

insert into public.products
  (slug, name, category_id, price, description, image_path, featured)
values
${PRODUCTS.map(
  (p) =>
    `  (${q(p.slug)}, ${q(p.name)},\n   (select id from public.categories where slug = ${q(p.category)}),\n   ${p.price}, ${q(p.description)},\n   ${q(p.image)}, ${p.featured ? "true" : "false"})`
).join(",\n")}
on conflict (slug) do update set
  name        = excluded.name,
  category_id = excluded.category_id,
  price       = excluded.price,
  description = excluded.description,
  image_path  = excluded.image_path,
  featured    = excluded.featured;

-- Product variants (sizes) --------------------------------------------------
--
-- stock is seeded at ${SEED_STOCK} per size as a placeholder.

insert into public.product_variants (product_id, size, sort_order, stock) values
${variantRows.join(",\n")}
on conflict (product_id, size) do update set
  sort_order = excluded.sort_order;
`;

  await writeFile(OUT, sql, "utf8");
  console.log(
    `\nWrote ${OUT}\n  ${PRODUCTS.length} products, ${CATEGORIES.length} categories, ${variantRows.length} variants`
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
